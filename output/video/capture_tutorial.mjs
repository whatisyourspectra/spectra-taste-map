import { chromium } from '/tmp/spectra-ui-check/node_modules/playwright/index.mjs';
const browser = await chromium.launch({headless:true, executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
const page = await browser.newPage({viewport:{width:1440,height:1000},locale:'ko-KR'});
page.setDefaultTimeout(4000);
await page.goto('https://www.tunemymusic.com/ko/transfer',{waitUntil:'domcontentloaded',timeout:30000});
await page.waitForTimeout(2000);
await page.getByText('좋아요',{exact:true}).click().catch(()=>{});
await page.screenshot({path:'output/video/tunemymusic-source.png'});
console.log('IMAGES',await page.locator('img').evaluateAll(es=>es.slice(0,15).map(e=>({alt:e.alt,src:e.src,html:e.parentElement.outerHTML.slice(0,650)}))));
await page.getByText('자유 텍스트',{exact:true}).click();
console.log('FREE TEXT',await page.locator('body').innerText());
console.log('INPUTS',await page.locator('input,textarea,button').evaluateAll(es=>es.map(e=>({tag:e.tagName,type:e.type,placeholder:e.placeholder,text:e.innerText}))));
await page.screenshot({path:'output/video/tunemymusic-free-text.png'});
await page.locator('textarea').fill('The Beatles - Hey Jude\nBeyoncé - Formation\nDaft Punk - One More Time');
await page.getByText('곡 목록 변환',{exact:true}).click();
await page.waitForTimeout(1800);
console.log('AFTER CONVERT',await page.locator('body').innerText());
await page.screenshot({path:'output/video/tunemymusic-playlist.png'});
console.log('BUTTONS',await page.locator('button').allTextContents());
await page.getByText(/목적지 선택|대상 선택|다음/).first().click().catch(()=>{});
await page.waitForTimeout(1200);
console.log('DESTINATION',await page.locator('body').innerText());
await page.screenshot({path:'output/video/tunemymusic-destination.png'});
await page.getByText('파일 내보내기',{exact:true}).click();
await page.waitForTimeout(1200);
console.log('EXPORT',await page.locator('body').innerText());
await page.screenshot({path:'output/video/tunemymusic-export.png'});
await page.locator('#csv').check();
await page.screenshot({path:'output/video/tunemymusic-csv-selected.png'});
await page.getByRole('button',{name:'내보내다',exact:true}).click();
await page.waitForTimeout(1800);
await page.screenshot({path:'output/video/tunemymusic-complete.png'});
console.log('AFTER EXPORT',await page.locator('body').innerText());
console.log('AFTER EXPORT BUTTONS',await page.locator('button').allTextContents());
const downloadPromise = page.waitForEvent('download',{timeout:15000}).catch(()=>null);
await page.getByRole('button',{name:'전송 시작',exact:true}).click();
await page.waitForTimeout(2500);
await page.screenshot({path:'output/video/tunemymusic-download.png'});
console.log('AFTER START',await page.locator('body').innerText());
const download = await downloadPromise;
if(download) { await download.saveAs('output/video/tunemymusic-example.csv'); console.log('FILE',download.suggestedFilename()); }
console.log('EXPORT ELEMENTS',await page.locator('button,input,label').evaluateAll(es=>es.map(e=>({tag:e.tagName,text:e.innerText,type:e.type,html:e.outerHTML.slice(0,300)}))));
const spotify = await browser.newPage({viewport:{width:1440,height:1000},locale:'ko-KR'});
await spotify.goto('https://www.tunemymusic.com/ko/transfer',{waitUntil:'domcontentloaded',timeout:30000});
await spotify.waitForTimeout(2000);
await spotify.getByText('좋아요',{exact:true}).click().catch(()=>{});
const popupPromise = spotify.waitForEvent('popup',{timeout:10000}).catch(()=>null);
await spotify.getByRole('button',{name:'Spotify',exact:true}).click();
const popup = await popupPromise;
if(popup) {
 await popup.waitForLoadState('domcontentloaded');
 await popup.waitForTimeout(2000);
 console.log('POPUP',popup.url(),(await popup.locator('body').innerText()).slice(0,2000));
 await popup.screenshot({path:'output/video/tunemymusic-login.png'});
}
await spotify.waitForTimeout(1200);
console.log('SPOTIFY',await spotify.locator('body').innerText());
await spotify.screenshot({path:'output/video/tunemymusic-connect.png'});
await browser.close();
