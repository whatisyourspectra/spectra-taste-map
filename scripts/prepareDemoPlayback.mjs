// Status is read-only. --prepare spends at most --limit search requests;
// --verify refreshes existing IDs in batches without using search.list.
import 'dotenv/config';
import { writeFile, rename } from 'node:fs/promises';
import { parseArgs } from 'node:util';
import { DEMO_UNIVERSES } from '../src/taste/demoUniverses.js';
import { DEMO_YOUTUBE_MATCHES } from '../src/server/data/demoYouTubeMatches.js';
import { createYouTubeResolver } from '../src/server/youtube.js';
import { YOUTUBE_MATCH_TTL_MS, youtubeMatchKey, isFreshYouTubeMatch } from '../src/audio/youtubeCachePolicy.js';

const { values } = parseArgs({ options: {
  prepare: { type: 'boolean', default: false }, verify: { type: 'boolean', default: false },
  limit: { type: 'string', default: '40' }, region: { type: 'string' },
} });
const region = String(values.region || process.env.YOUTUBE_REGION || 'KR').toUpperCase();
const limit = Number(values.limit);
if (!Number.isInteger(limit) || limit < 1 || limit > 240) throw new Error('--limit must be an integer from 1 to 240.');
const apiKey = process.env.YOUTUBE_API_KEY || '';
const target = new URL('../src/server/data/demoYouTubeMatches.js', import.meta.url);
const matches = { ...DEMO_YOUTUBE_MATCHES.matches };
// Round-robin entry themes: prepare the most visible songs of all three cards first.
const tracks = Array.from({ length: Math.max(...DEMO_UNIVERSES.map(u => u.tracks.length)) }, (_, i) =>
  DEMO_UNIVERSES.flatMap(universe => universe.tracks[i] ? [universe.tracks[i]] : [])).flat();
const keyFor = track => youtubeMatchKey(track.artists, track.name, region);

function report() {
  const ready = tracks.filter(track => matches[keyFor(track)]?.video && isFreshYouTubeMatch(matches[keyFor(track)]));
  console.log(JSON.stringify({ total: tracks.length, ready: ready.length, remaining: tracks.length - ready.length,
    region, mode: values.prepare ? 'prepare' : values.verify ? 'verify' : 'status',
    searchBudget: values.prepare ? limit : 0 }, null, 2));
}

async function save() {
  const fresh = Object.fromEntries(Object.entries(matches).filter(([, match]) => isFreshYouTubeMatch(match)));
  const content = '// Generated by scripts/prepareDemoPlayback.mjs. Public video metadata only;\n'
    + '// no audio/video files or credentials. Expired matches must be refreshed.\n'
    + `export const DEMO_YOUTUBE_MATCHES = ${JSON.stringify({ version: 1, region, matches: fresh }, null, 2)};\n`;
  const temp = new URL(`${target.href}.tmp`);
  await writeFile(temp, content);
  await rename(temp, target);
}

async function verify(existing) {
  let requests = 0;
  const found = new Map();
  const ids = [...new Set(existing.flatMap(([, match]) => (match.candidates || [match.video]).map(video => video.videoId)))];
  for (let start = 0; start < ids.length; start += 50) {
    const batch = ids.slice(start, start + 50);
    const params = new URLSearchParams({ part: 'snippet,status,contentDetails',
      id: batch.join(','), key: apiKey });
    const response = await fetch(`https://www.googleapis.com/youtube/v3/videos?${params}`, { signal: AbortSignal.timeout(15000) });
    requests++;
    const body = await response.json();
    if (!response.ok) throw new Error(body?.error?.message || `Video verification failed (${response.status}).`);
    for (const item of body.items || []) found.set(item.id, item);
  }
  for (const [key, match] of existing) {
    let chosen = null;
    for (const video of match.candidates || [match.video]) {
      const item = found.get(video.videoId);
      const restrictions = item?.contentDetails?.regionRestriction;
      const unavailable = !item || !item.status?.embeddable
        || !['public', 'unlisted'].includes(item.status.privacyStatus)
        || restrictions?.blocked?.includes(region)
        || (restrictions?.allowed && !restrictions.allowed.includes(region))
        || item.contentDetails?.contentRating?.ytRating === 'ytAgeRestricted';
      if (unavailable) continue;
      chosen = item;
      break;
    }
    if (!chosen) {
      console.log(`No embeddable candidate in ${region}: ${key}`);
      delete matches[key];
    } else {
      const fetchedAt = Date.now();
      matches[key] = { video: { videoId: chosen.id, title: chosen.snippet.title, channelTitle: chosen.snippet.channelTitle,
        thumbnailUrl: chosen.snippet.thumbnails?.medium?.url || chosen.snippet.thumbnails?.default?.url || null },
        fetchedAt, expiresAt: fetchedAt + YOUTUBE_MATCH_TTL_MS };
    }
  }
  console.log(`Video validation requests: ${requests}; search requests: 0.`);
}

async function main() {
  report();
  if (!values.prepare && !values.verify) return;
  if (!apiKey || apiKey.startsWith('your_')) throw new Error('Set YOUTUBE_API_KEY on the server before preparing playback.');
  const existing = Object.entries(matches).filter(([key, match]) => key.startsWith(`${region}|`) && match?.video?.videoId);
  if (values.verify) {
    await verify(existing);
    await save();
    report();
    return;
  }
  const expired = existing.filter(([, match]) => !isFreshYouTubeMatch(match));
  if (expired.length) await verify(expired);
  const resolver = createYouTubeResolver({ apiKey, region, initialMatches: matches });
  const missing = tracks.filter(track => !resolver.peek(track.artists, track.name));
  let searches = 0;
  try {
    for (const track of missing.slice(0, limit)) {
      searches++;
      const match = await resolver.resolve(track.artists, track.name);
      matches[keyFor(track)] = match;
      await save(); // Preserve completed matches if a later request exhausts quota.
      console.log(`[${searches}/${limit}] ${track.artists} — ${track.name}: ${match.video ? 'matched' : 'no match'}`);
      await new Promise(resolve => setTimeout(resolve, 250));
    }
  } catch (error) {
    console.error(`Stopped after ${searches} search attempts: ${error.code || ''} ${error.message}`);
    process.exitCode = 1;
  }
  const fresh = Object.entries(matches).filter(([key, match]) => key.startsWith(`${region}|`) && match?.video?.videoId && isFreshYouTubeMatch(match));
  if (fresh.length) {
    await verify(fresh);
    await save();
  }
  console.log(`Search requests attempted this run: ${searches}.`);
  report();
}

main().catch(error => { console.error(error.message); process.exitCode = 1; });
