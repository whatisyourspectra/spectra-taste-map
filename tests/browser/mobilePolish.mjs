// Local fixtures: mobile selection, stable action positions and saved feedback.
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_EXECUTABLE || undefined });
const base = process.env.BASE_URL || 'http://127.0.0.1:5188';
const output = 'output/review/mobile-polish';
await mkdir(output, { recursive: true });
const names = ['Sunsetz', 'The Less I Know the Better — A Very Long Song Title for a Quiet Evening', 'Movie', 'Space Song', 'Show Me How', 'Get Lucky'];
const artists = ['Cigarettes After Sex', 'Tame Impala', 'Tom Misch', 'Beach House', 'Men I Trust', 'Daft Punk'];
const covers = ['cigarettes-after-sex', 'currents', 'geography', 'depression-cherry', 'show-me-how', 'discovery'];
const tracks = Array.from({ length: 36 }, (_, i) => ({ id: `polish-${i}`, name: `${names[i % 6]}${i >= 6 ? ` ${i}` : ''}`, artists: artists[i % 6], coverUrl: `/demo-covers/${covers[i % 6]}.jpg`, genres: [['dream pop'], ['jazz'], ['electronic']][i % 3], valence: .5, energy: .6 }));
const recommendations = tracks.slice(0, 3).map((track, i) => ({ ...track, id: `new-${i}`, name: i === 0 ? 'South of the River' : `${track.name} — Discovery` }));
const errors = [], findings = [];
async function contained(locator, height) {
    const box = await locator.boundingBox();
    assert.ok(box && box.y >= 0 && box.y + box.height <= height + 1, JSON.stringify(box));
    return box;
}
try {
    for (const viewport of [{ width: 320, height: 640 }, { width: 390, height: 844 }, { width: 430, height: 932 }]) {
        const page = await browser.newPage({ viewport, isMobile: true, hasTouch: true });
        page.on('pageerror', error => errors.push(error.message));
        await page.addInitScript(tracks => {
            sessionStorage.setItem('spectra:taste:v5', JSON.stringify({ tracks, mapId: 'mobile-polish', featuresSource: 'lastfm', stats: { isDemo: false } }));
        }, tracks);
        await page.route(/\/src\/auth\/supabaseClient\.js(?:\?.*)?$/, route => route.fulfill({ contentType: 'application/javascript', body: 'export const supabase=null;export function finishGoogleLogin(){return Promise.reject();}' }));
        await page.route('**/api/discover?**', route => route.fulfill({ json: { tracks: recommendations } }));
        await page.goto(base + '/taste-map');
        await page.locator('.public-map-peek-tracks > button').first().waitFor();
        await page.evaluate(() => document.fonts.ready);
        const nav = page.locator('.mtm-bottom-nav');
        const dock = await contained(nav, viewport.height);
        assert.ok(dock.x >= 16 && dock.x + dock.width <= viewport.width - 16, 'Floating menu needs space on both sides');
        assert.ok(viewport.height - dock.y - dock.height >= 11, 'Floating menu needs space below it');
        assert.equal(await nav.evaluate(element => getComputedStyle(element).position), 'absolute', 'Dock must overlay the page rather than consume a flex row');
        assert.ok(Math.abs((await page.locator('.public-map-inspector').boundingBox()).y + (await page.locator('.public-map-inspector').boundingBox()).height - viewport.height) <= 1, 'Map panel background must extend behind the dock');
        assert.ok((await nav.getByRole('button').first().boundingBox()).height >= 44, 'Tab touch targets must remain at least 44px');
        await page.screenshot({ path: `${output}/map-${viewport.width}.png` });
        await page.locator('.public-map-peek-tracks > button').first().click();
        const panel = page.locator('.public-map-track');
        await panel.waitFor();
        await page.waitForTimeout(350);
        const firstActions = await contained(panel.locator('.public-map-track-actions'), viewport.height);
        const next = page.getByRole('button', { name: '다음 내 곡', exact: true });
        await contained(next, viewport.height);
        await next.click();
        await page.waitForTimeout(350);
        assert.equal(await panel.locator('h2').textContent(), names[1]);
        const longActions = await contained(panel.locator('.public-map-track-actions'), viewport.height);
        assert.ok(Math.abs(longActions.y - firstActions.y) <= 1, 'Long song titles must not move the actions');
        const navBox = await contained(nav, viewport.height);
        const panelBox = await panel.boundingBox();
        assert.ok(panelBox.y + panelBox.height <= navBox.y + 1, 'Song actions must remain above navigation');
        const youtube = panel.getByRole('link', { name: /YouTube/ });
        assert.ok((await youtube.getAttribute('href')).includes(encodeURIComponent(names[1])));
        await page.getByRole('button', { name: '관심 표시', exact: true }).click();
        assert.equal(await page.getByRole('button', { name: '관심 표시됨', exact: true }).getAttribute('aria-pressed'), 'true');
        await page.getByRole('button', { name: '취향 반응 안내 닫기' }).click();
        await page.screenshot({ path: `${output}/selected-${viewport.width}.png` });
        await page.getByRole('button', { name: '비슷한 곡 찾기', exact: true }).click();
        const card = page.locator('.mtm-drop-card');
        await card.waitFor();
        const discoveryArea = await page.locator('.mtm-discovery').boundingBox();
        assert.ok(Math.abs(discoveryArea.y + discoveryArea.height - viewport.height) <= 1, 'Discovery must scroll to the screen edge behind the dock');
        const discoveryDock = await nav.boundingBox();
        assert.deepEqual(discoveryDock, dock, 'Floating menu must stay in place between tabs');
        assert.equal(await nav.evaluate(element => element.style.getPropertyValue('--mtm-active-tab')), '1');
        await card.locator('.mtm-drop-decisions').evaluate(element => element.scrollIntoView({ block: 'end', behavior: 'instant' }));
        await page.waitForTimeout(350);
        const add = card.getByRole('button', { name: '내 음악에 추가', exact: true });
        const addBefore = await add.boundingBox();
        await card.getByRole('button', { name: '관심 표시', exact: true }).click();
        await page.waitForTimeout(350);
        const addAfter = await add.boundingBox();
        assert.ok(Math.abs(addBefore.y - addAfter.y) <= 1, 'Next discovery and feedback must not move the primary action');
        await add.click();
        await page.locator('.mtm-discovery-message').filter({ hasText: '내 지도에 음악을 추가했어요.' }).waitFor();
        await page.waitForTimeout(350);
        await page.screenshot({ path: `${output}/discover-${viewport.width}.png` });
        assert.ok(await page.evaluate(() => JSON.parse(sessionStorage.getItem('spectra:taste:v5')).tracks.some(track => track.id === 'new-1')));
        await nav.getByRole('button', { name: '내 지도', exact: true }).click();
        await page.locator('.mtm-tab-map').waitFor();
        assert.equal(await panel.locator('h2').textContent(), names[1]);
        await nav.getByRole('button', { name: '오늘', exact: true }).click();
        await page.locator('.mtm-tab-today').waitFor();
        assert.deepEqual(await nav.boundingBox(), dock, 'Today must keep the same dock position');
        assert.equal(await nav.evaluate(element => element.style.getPropertyValue('--mtm-active-tab')), '2');
        const today = page.locator('.mtm-today');
        const todayArea = await today.boundingBox();
        assert.ok(Math.abs(todayArea.y + todayArea.height - viewport.height) <= 1, 'Today must extend behind the dock instead of stopping above it');
        // Position calendar rows behind the overlay to catch the original cutoff.
        await today.evaluate((element, navTop) => {
            const grid = element.querySelector('.mcc-days-grid');
            element.scrollTop += grid.getBoundingClientRect().top - (navTop - 120);
        }, dock.y);
        assert.equal(await page.evaluate(y => Boolean(document.elementFromPoint(5, y)?.closest('.mtm-today')), dock.y + dock.height / 2), true, 'Content beside the dock must remain visible and scrollable');
        assert.equal(await page.evaluate(({ x, y }) => Boolean(document.elementFromPoint(x, y)?.closest('.mtm-bottom-nav')), { x: dock.x + dock.width / 2, y: dock.y + dock.height / 2 }), true, 'Tab buttons must remain above the content');
        await page.screenshot({ path: `${output}/today-${viewport.width}.png` });
        await today.evaluate(element => { element.scrollTop = element.scrollHeight; });
        const endNote = await today.locator('.mtm-storage-note').boundingBox();
        assert.ok(endNote.y + endNote.height < dock.y, 'Last content must scroll above the dock');
        await today.getByRole('button', { name: '내 순간 직접 적기', exact: false }).click();
        const moment = today.getByRole('textbox', { name: '나의 순간', exact: true });
        await moment.fill('저녁 산책');
        await page.setViewportSize({ width: viewport.width, height: 320 });
        await page.waitForFunction(() => document.querySelector('.mobile-taste-map')?.dataset.compactViewport === 'true');
        assert.equal(await nav.isVisible(), false, 'Dock must give focused inputs room when the keyboard reduces the viewport');
        await page.setViewportSize(viewport);
        await moment.blur();
        await nav.waitFor({ state: 'visible' });
        assert.equal(await moment.inputValue(), '저녁 산책');
        await nav.getByRole('button', { name: '내 지도', exact: true }).click();
        await page.locator('.mtm-tab-map').waitFor();
        await page.locator('.mobile-taste-map').evaluate(element => element.style.setProperty('--mtm-nav-inset', '34px'));
        await page.waitForTimeout(350);
        const safeDock = await contained(nav, viewport.height);
        assert.ok(viewport.height - safeDock.y - safeDock.height >= 33, 'Dock must respect a larger bottom safe area');
        const safePanel = await panel.boundingBox();
        assert.ok(safePanel.y + safePanel.height <= safeDock.y + 1, `Safe area must not cause the dock to cover song controls: ${JSON.stringify({safePanel,safeDock})}`);
        await page.locator('.mobile-taste-map').evaluate(element => element.style.removeProperty('--mtm-nav-inset'));
        await page.emulateMedia({ reducedMotion: 'reduce' });
        assert.equal(await page.locator('.mtm-track-identity').evaluate(element => getComputedStyle(element).animationName), 'none');
        assert.equal(await nav.evaluate(element => getComputedStyle(element, '::before').transitionDuration), '0s');
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
        findings.push({ viewport, stableActions: true, savedFeedback: true, selectionPreserved: true, reducedMotion: true });
        await page.close();
    }
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ findings, errors }, null, 2));
} finally { await browser.close(); }
